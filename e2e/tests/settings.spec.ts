import { card, cards, expect, HOSTS, open, openOptions, openSettings, seed, test, toast } from './fixtures'

/* The settings panel (stored in localStorage) and the language switch. */

test('the panel opens from the header and closes with its X or a click beside it', async ({ page, baseURL }) => {
  await open(page, baseURL)
  const panel = await openSettings(page)
  await panel.getByRole('button', { name: 'Close' }).click()
  await expect(panel).not.toHaveClass(/is-open/)
  await openSettings(page)
  await page.locator('#settingsOverlay').click({ position: { x: 100, y: 400 } })
  await expect(panel).not.toHaveClass(/is-open/)
})

test('theme: light and dark stay after a reload; auto follows the system', async ({ page, baseURL }) => {
  await open(page, baseURL)
  const html = page.locator('html')
  await expect(html).toHaveAttribute('data-theme', 'dark')
  let panel = await openSettings(page)
  await panel.getByLabel('Theme').selectOption('Light')
  await expect(html).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(html).toHaveAttribute('data-theme', 'light')
  await page.emulateMedia({ colorScheme: 'dark' })
  panel = await openSettings(page)
  await expect(panel.getByLabel('Theme')).toHaveValue('light')
  await panel.getByLabel('Theme').selectOption('Auto')
  await expect(html).toHaveAttribute('data-theme', 'dark')
  await page.emulateMedia({ colorScheme: 'light' })
  await page.reload()
  await expect(html).toHaveAttribute('data-theme', 'light')
})

test('compact view: a list, also after a reload', async ({ page, baseURL }) => {
  await open(page, baseURL)
  const panel = await openSettings(page)
  // The checkbox itself is hidden; its switch is the label around it.
  await panel.locator('label.wol-toggle').filter({ has: page.getByLabel('Compact view') }).click()
  await expect(panel.getByLabel('Compact view')).toBeChecked()
  await expect(page.locator('body')).toHaveClass(/view-compact/)
  await page.reload()
  await expect(page.locator('body')).toHaveClass(/view-compact/)
  await expect(cards(page)).toHaveCount(HOSTS.length)
})

test('check interval "Disabled": no status checks; another interval starts them again', async ({ page, baseURL }) => {
  let checks = 0
  page.on('request', (r) => /aop=HOST\.CHECK/.test(r.url()) && checks++)
  await page.clock.install()
  await open(page, baseURL, { settings: { checkInterval: 0 } })
  await page.clock.runFor(30_000)
  await page.evaluate(() => 0)
  expect(checks).toBe(0)
  await expect(page.locator('#hostGrid .wol-card.is-checking')).toHaveCount(HOSTS.length)
  const panel = await openSettings(page)
  await expect(panel.getByLabel('Check interval')).toHaveValue('0')
  await panel.getByLabel('Check interval').selectOption('2s')
  await expect(card(page, 'NAS (backups)')).toHaveClass(/is-online/)
})

test('auto-refresh off: the page does not load the hosts until "Load Configuration"', async ({ page, baseURL }) => {
  let loads = 0
  page.on('request', (r) => /aop=CONFIG\.GET/.test(r.url()) && loads++)
  await seed(HOSTS, baseURL!)
  await page.addInitScript(() => localStorage.setItem('wol_settings', JSON.stringify({ autoRefresh: false })))
  await page.clock.install()
  await page.goto('/')
  await page.clock.runFor(5_000)
  await page.evaluate(() => 0)
  expect(loads).toBe(0)
  await expect(cards(page)).toHaveCount(0)
  await expect(page.locator('#statTotal')).toHaveText('0')
  await (await openOptions(page)).getByRole('link', { name: 'Load Configuration', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Replace Existing' }).click()
  await expect(cards(page)).toHaveCount(HOSTS.length)
})

test('default port and CIDR fill the Add Host dialog; an out-of-range value is not stored', async ({ page, baseURL }) => {
  await open(page, baseURL)
  let panel = await openSettings(page)
  await panel.getByLabel('Default port').fill('7')
  await panel.getByLabel('Default CIDR').fill('16')
  await panel.getByLabel('Default CIDR').press('Tab')
  await panel.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('button', { name: 'Add Host' }).click()
  const dialog = page.getByRole('dialog', { name: 'Add Host' })
  await expect(dialog.getByLabel('Port')).toHaveValue('7')
  await expect(dialog.getByLabel('Subnet CIDR')).toHaveValue('16')
  await page.reload()
  panel = await openSettings(page)
  await panel.getByLabel('Default port').fill('70000')
  await panel.getByLabel('Default CIDR').fill('33')
  await panel.getByLabel('Default CIDR').press('Tab')
  await page.reload()
  panel = await openSettings(page)
  await expect(panel.getByLabel('Default port')).toHaveValue('7')
  await expect(panel.getByLabel('Default CIDR')).toHaveValue('16')
})

test.describe('toast duration', () => {
  test('3 seconds: a toast goes away by itself', async ({ page, baseURL }) => {
    await page.clock.install()
    await open(page, baseURL, { settings: { toastDuration: 3000 } })
    await card(page, 'Office workstation').getByRole('button', { name: 'Wake' }).click()
    await expect(toast(page)).toHaveCount(1)
    await page.clock.runFor(2_000)
    await expect(toast(page)).toHaveCount(1)
    await page.clock.runFor(1_500)
    await expect(toast(page)).toHaveCount(0)
  })

  test('persistent: a toast stays', async ({ page, baseURL }) => {
    await page.clock.install()
    await open(page, baseURL)
    const panel = await openSettings(page)
    await panel.getByLabel('Toast duration').selectOption('Persistent')
    await panel.getByRole('button', { name: 'Close' }).click()
    await card(page, 'Office workstation').getByRole('button', { name: 'Wake' }).click()
    await expect(toast(page)).toHaveCount(1)
    await page.clock.runFor(60_000)
    await expect(toast(page)).toHaveCount(1)
  })
})

test.describe('language', () => {
  const importLink = (page: import('@playwright/test').Page) => page.locator('#importConfig')

  test('Settings › Display language: German and Spanish, kept after a reload', async ({ page, baseURL }) => {
    await open(page, baseURL)
    let panel = await openSettings(page)
    await panel.getByLabel('Display language').selectOption('Deutsch')
    await expect(importLink(page)).toHaveText('Konfiguration importieren')
    await expect(page.locator('label[for="mac"]')).toHaveText('MAC-Adresse')
    await page.reload()
    await expect(importLink(page)).toHaveText('Konfiguration importieren')
    panel = await openSettings(page)
    await panel.getByLabel('Display language').selectOption('Español')
    await expect(importLink(page)).toHaveText('Importar configuración')
    await expect(page.locator('label[for="mac"]')).toHaveText('Dirección MAC')
  })

  test('the footer flags switch the language, and the choice is kept like the setting', async ({ page, baseURL }) => {
    await open(page, baseURL)
    await page.getByRole('link', { name: 'Deutsch' }).click()
    await expect(importLink(page)).toHaveText('Konfiguration importieren')
    let panel = await openSettings(page)
    await expect(panel.getByLabel('Display language')).toHaveValue('de-DE')
    await page.reload()
    await expect(importLink(page)).toHaveText('Konfiguration importieren')
    await page.getByRole('link', { name: 'Español' }).click()
    await expect(importLink(page)).toHaveText('Importar configuración')
    await page.getByRole('link', { name: 'English' }).click()
    await expect(importLink(page)).toHaveText('Import Configuration')
    panel = await openSettings(page)
    await expect(panel.getByLabel('Display language')).toHaveValue('en-US')
  })
})
